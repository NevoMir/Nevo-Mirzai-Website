/** The 7 rows of the glyph for `ch`, or null for a character the font does not have (a space is drawn as a gap). */
export function glyphRows(ch: string): readonly string[] | null {
    return Object.prototype.hasOwnProperty.call(GLYPHS, ch) ? GLYPHS[ch] : null;
}

