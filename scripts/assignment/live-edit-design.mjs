for (const p of base.parts) console.log(`   ${p.name.padEnd(28)} ${p.shape.padEnd(9)} size ${p.size.map(Math.round).join("x").padEnd(14)} at ${p.position.map(Math.round).join(",").padEnd(16)} ${p.color}`);

// ---- helpers for the predicates
const key = (n) => n.toLowerCase().replace(/\s+/g, " ");
const top = (p) => p.position[2] + p.size[2] / 2;
const byName = (d) => new Map(d.parts.map((p) => [key(p.name), p]));
const hue = (hex) => {
    const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b), d = mx - mn;
    if (d < 0.04) return { h: -1, s: 0, v: mx };
    const h = mx === r ? ((g - b) / d + 6) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
    return { h: h * 60, s: d / mx, v: mx };
};
const isGreen = (hex) => { const c = hue(hex); return c.h >= 75 && c.h <= 170 && c.s > 0.25; };
const isRed = (hex) => { const c = hue(hex); return (c.h <= 18 || c.h >= 340) && c.s > 0.4; };
const find = (d, re) => d.parts.filter((p) => re.test(p.name));
/**
 * The cleaner may shrink the whole object to fit the 1000 mm cube ("scaled to 91%") and always re-centres and re-grounds it, so an untouched part
 * is the same part under that map, not at the same millimetre. The map is read off the seat, which none of these edits move.
 */
function frameMap(a, b) {
    const sa = find(a, /seat/i)[0], sb = byName(b).get(key(sa?.name ?? ""));
    if (!sa || !sb) return { s: 1, off: [0, 0, 0] };
    const s = sb.size[0] / sa.size[0];
    return { s, off: [0, 1, 2].map((i) => sb.position[i] - s * sa.position[i]) };
}
/** p of the old design and q of the new one are the same part (shape, size, place, turn, colour) under the map; colour may be ignored. */
const alike = (p, q, m, { colour = true } = {}) =>
    !!q && p.shape === q.shape && [0, 1, 2].every((i) => Math.abs(q.size[i] - m.s * p.size[i]) <= 1.5 && Math.abs(q.position[i] - (m.s * p.position[i] + m.off[i])) <= 2 && Math.abs(q.rotation[i] - p.rotation[i]) <= 0.6) && (!colour || p.color === q.color);
const unchangedExcept = (a, b, names, opts) => {
    const m = frameMap(a, b), mb = byName(b);
    return a.parts.filter((p) => !names.has(key(p.name))).every((p) => alike(p, mb.get(key(p.name)), m, opts));
};

const CASES = [
    {
        id: "taller-back", text: "make the backrest taller",
        check: (a, b) => {
            const m = frameMap(a, b), mb = byName(b);
            const ba = find(a, /back|rail|slat/i), bb = find(b, /back|rail|slat/i);
            const seatTopB = Math.max(...find(b, /seat/i).map(top)), seatTopA = Math.max(...find(a, /seat/i).map(top));
            const moved = a.parts.filter((p) => !alike(p, mb.get(key(p.name)), m)).map((p) => key(p.name));
            return [
                ["the backrest reaches higher above the seat (>= 40 mm in the old scale)", ba.length > 0 && (Math.max(...bb.map(top)) - seatTopB) / m.s >= Math.max(...ba.map(top)) - seatTopA + 40],
                ["same number of parts", a.parts.length === b.parts.length],
                ["only back parts changed (seat, legs and arms the same under the map)", moved.every((n) => /back|rest|slat|splat|rail|spindle|upright/i.test(n))],
                ["the seat did not change", find(a, /seat/i).every((p) => alike(p, mb.get(key(p.name)), m))],
            ];
        },
    },
    {
        id: "cup-holder", text: "add a cup holder on the right armrest",
        check: (a, b) => {
            const ma = byName(a), mp = frameMap(a, b);
            const added = b.parts.filter((p) => !ma.has(key(p.name)));
            const arm = find(b, /right.*arm|arm.*right/i).filter((p) => !/post|support|leg/i.test(p.name));
            const near = (p) => arm.some((q) => Math.abs(p.position[0] - q.position[0]) < q.size[0] / 2 + 120 && Math.abs(p.position[1] - q.position[1]) < q.size[1] / 2 + 120);
            return [
                ["1 to 4 parts added", added.length >= 1 && added.length <= 4],
                ["the new parts are named like a cup holder", added.some((p) => /cup|holder|ring|cylinder|drink/i.test(p.name))],
                ["nothing removed", a.parts.every((p) => byName(b).has(key(p.name)))],
                ["every old part is the same under the map", unchangedExcept(a, b, new Set())],
                ["the new parts sit on the right armrest", added.length > 0 && added.some(near)],
            ];
        },
    },
    {
        id: "remove-left-arm", text: "remove the left armrest including its posts",
        check: (a, b) => {
            const left = find(a, /left/i).filter((p) => /arm|post|support/i.test(p.name));
            const leftNames = new Set(left.map((p) => key(p.name)));
            const m = frameMap(a, b), mb = byName(b);
            return [
                ["at least 2 left armrest parts existed", left.length >= 2],
                ["every left armrest part and post is gone", left.every((p) => !mb.has(key(p.name)))],
                ["nothing else removed", a.parts.every((p) => leftNames.has(key(p.name)) || mb.has(key(p.name)))],
                ["the right armrest is the same under the map", find(a, /right/i).filter((p) => /arm|post|support/i.test(p.name)).every((p) => alike(p, mb.get(key(p.name)), m))],
                ["the rest is the same under the map", unchangedExcept(a, b, leftNames)],
            ];
        },
    },
    {
        id: "repaint-all", text: "paint the whole chair dark green",
        check: (a, b) => {
            const m = frameMap(a, b), mb = byName(b);
            return [
                ["every part is green now", b.parts.length > 0 && b.parts.every((p) => isGreen(p.color))],
                ["dark (value <= 0.6)", b.parts.every((p) => hue(p.color).v <= 0.6)],
                ["shapes, sizes and places untouched", a.parts.length === b.parts.length && a.parts.every((p) => alike(p, mb.get(key(p.name)), m, { colour: false }))],
            ];
        },
    },
    {
        id: "repaint-seat", text: "make the seat red and leave everything else as it is",
        check: (a, b) => {
            const seats = new Set(find(a, /seat/i).map((p) => key(p.name)));
            const mb = byName(b), m = frameMap(a, b);
            return [
                ["the seat is red", seats.size > 0 && [...seats].every((n) => mb.get(n) && isRed(mb.get(n).color))],
                ["every other part is the same under the map", unchangedExcept(a, b, seats)],
                ["the seat itself did not move", find(a, /seat/i).every((p) => alike(p, mb.get(key(p.name)), m, { colour: false }))],
                ["same number of parts", a.parts.length === b.parts.length],
            ];
        },
    },
];

// ---- run them, one after the other, each on the original model (the project allows one running edit at a time)
const results = [];
const made = [];
let predicates = 0, passed = 0;
const only = process.env.CASES?.split(",");
const afters = {};
for (const T of CASES) {
    if (only && !only.includes(T.id)) continue;
    const started = Date.now();
    const res = await call("POST", `/models/${baseId}/edits`, { instruction: T.text, target: "design" });
    if (res.status !== 201) {
        console.log(`${T.id.padEnd(16)} HTTP ${res.status} ${JSON.stringify(res.json)?.slice(0, 200)}`);
        results.push({ id: T.id, status: res.status, failed: ["could not start"] });
        predicates += 3;
        continue;
    }
    const job = await untilDone(res.json.job.id);
    const ms = Date.now() - started;
    if (job?.status !== "succeeded") {
        console.log(`${T.id.padEnd(16)} job ${job?.status} in ${ms} ms: ${job?.error ?? ""}`);
        results.push({ id: T.id, status: job?.status, ms, failed: ["job did not succeed"], error: job?.error });
        predicates += 3;
        continue;
    }
    if (!job.model) {
        console.log(`${T.id.padEnd(16)} no version: ${JSON.stringify(job.edit?.result)?.slice(0, 300)}`);
        results.push({ id: T.id, status: "no-model", ms, failed: ["no new version"], result: job.edit?.result });
        predicates += 3;
        continue;
    }
    made.push(job.model.id);
    const after = await designOf(job.model.id);
    afters[T.id] = after;
    const checks = after ? T.check(base, after) : [["the new file reads as a design", false]];
    const failed = checks.filter((c) => !c[1]).map((c) => c[0]);
    predicates += checks.length;
    passed += checks.length - failed.length;
    const meta = job.model.edit;
    results.push({ id: T.id, text: T.text, ms, passed: checks.length - failed.length, total: checks.length, failed, summary: meta?.summary, notes: meta?.notes, changes: meta?.changes, parts: after?.parts.length });
    console.log(`${T.id.padEnd(16)} ${checks.length - failed.length}/${checks.length}  ${(ms / 1000).toFixed(1)} s  "${T.text}"`);
    console.log(`                 "${(meta?.summary ?? "").slice(0, 120)}"  changed=${JSON.stringify(meta?.changes?.changed ?? [])} added=${JSON.stringify(meta?.changes?.added ?? [])} removed=${JSON.stringify(meta?.changes?.removed ?? [])}${meta?.notes?.length ? `  notes=${JSON.stringify(meta.notes)}` : ""}`);
    if (failed.length) console.log(`                 FAILED: ${failed.join("; ")}`);
}

// undo: deleting a version removes it, the source stays
let undone = 0;
for (const id of made) if ((await call("DELETE", `/models/${id}`)).status === 200) undone++;
const left = (await call("GET", `/projects/${projectId}`)).json?.project?.models?.filter((m) => m.kind === "edited").length;
console.log(`\nundo: ${undone}/${made.length} versions deleted, ${left} edited versions left`);
console.log(`${passed}/${predicates} predicates`);
if (process.env.LIVE_OUT) writeFileSync(process.env.LIVE_OUT, JSON.stringify({ baseId, projectId, base, afters, results, undone }, null, 1));
process.exit(passed >= predicates - 1 && undone === made.length ? 0 : 1);
