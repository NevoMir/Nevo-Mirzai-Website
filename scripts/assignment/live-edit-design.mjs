// The live check of the design edits (a Muse parts model changed by words) through a real `wrangler dev` with the key: a Muse model is generated
// first (one designer call), then five edits are asked of it through POST /models/:id/edits and the queue consumer. Each answer is judged by
// objective predicates on the parts of the new version (what must change, what must stay byte-identical). The edits are the acceptance suite of
// the spec (8.3): a taller backrest, a cup holder, the left armrest removed with its posts, a repaint of everything and a repaint of one part (both
// can use the `recolor` field of the patch). It costs real money: 1 generation and 5 edits, about $0.005 in all, 5 to 30 s each. Never calls Tencent.
//
//   LIVE=1 BASE=http://127.0.0.1:8761 node scripts/assignment/live-edit-design.mjs
//   (the server: a `wrangler dev` whose .dev.vars has OPENROUTER_API_KEY and no MOCK_PROVIDER, or MOCK_LLM=0 together with MOCK_PROVIDER=1)
//   CASES=taller-back,cup-holder  runs only these
//   MODEL=<model id>  reuses a model already generated in PROJECT=<project id> instead of generating one; LIVE_OUT=<file> writes every call as JSON.
//
// The key is never read here: only the server has it. The cost of an edit is read from the server log when LOG=<wrangler dev log file> is given.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
