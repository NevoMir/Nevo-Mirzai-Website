/** JSON with sorted keys, to compare two objects whatever order their keys were written in. */
const canonical = (value) => JSON.stringify(value, (_, v) => (v && typeof v === "object" && !Array.isArray(v) ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => (a < b ? -1 : 1))) : v));

/** The GLB bytes of a stored model (to upload it again). */
async function readBack(model) {
    return new Uint8Array(await (await fetch(`${BASE}${model.glb_url}`)).arrayBuffer());
}

/** The real analysis engine's summary (with stress) is accepted by the server's validators; skipped when the engine cannot load. */
async function engineRoundTrip(source) {
    section("the analysis engine's own summary passes the server's validators");
    try {
        const asm = await import("../../src/assignment/analysis/assembly.ts");
        const st = await import("../../src/assignment/analysis/stress.ts");
        const sample = await variant();
        const solver = await st.loadSolver(resolve(ROOT, "src/assignment/analysis/fem/vendor/lSolver.wasm"));
        const base = asm.analyzeAssembly(sample.descriptor, null, {});
        const result = st.applyStress(base, st.computeStress(base, solver));
        const summary = { ...result.summary, analyzed_at: new Date(Date.now() - 1000).toISOString() };
        check(`the engine computed a stress block (${solver.backend} solver)`, summary.stress?.analysed_blocks > 0, JSON.stringify(summary.stress));
        const put = await call("PUT", `/models/${source.id}/analysis`, { summary });
        check("PUT /analysis accepts it as is", put.status === 200 && put.json.model.analysis.stress?.max_utilisation === summary.stress.max_utilisation, `${put.status} ${JSON.stringify(put.json)?.slice(0, 200)}`);
        const meta = await metaFor(sample.descriptor, 1, { after_summary: summary, solver: solver.backend === "wasm" ? "awatif-wasm" : "awatif-ts" });
        const probe = await newProject("engine summary");
        const s = await insertSource(probe.id);
        if (s) {
            const out = await upload(s, writeAssemblyGlb(sample.descriptor, meta));
            check("a stabilized upload whose after_summary is the engine's is accepted", out.status === 201, `${out.status} ${JSON.stringify(out.json)?.slice(0, 200)}`);
        }
    } catch (err) {
        note(`the analysis engine could not run here (${String(err?.message ?? err).slice(0, 120)}): skipped`);
    }
}

